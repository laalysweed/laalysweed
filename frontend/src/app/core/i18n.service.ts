@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly STORAGE_KEY = 'y2.lang';
  readonly languages = LANGUAGES;

  readonly currentLang = signal<LangCode>(this.getInitialLang());

  readonly t = computed(() => {
    const code = this.currentLang();
    return TRANSLATIONS[code] ?? TRANSLATIONS.EN;
  });

  private getInitialLang(): LangCode {
    try {
      const saved = localStorage.getItem(this.STORAGE_KEY) as LangCode;
      if (saved && TRANSLATIONS[saved]) return saved;
    } catch {
      // Ignore
    }
    return 'EN';
  }

  setLanguage(code: string) {
    const upper = code.toUpperCase() as LangCode;
    if (TRANSLATIONS[upper]) {
      this.currentLang.set(upper);
      try {
        localStorage.setItem(this.STORAGE_KEY, upper);
      } catch {
        // Ignore
      }
      if (typeof document !== 'undefined') {
        document.documentElement.lang = upper.toLowerCase();
        document.documentElement.dir = upper === 'AR' ? 'rtl' : 'ltr';
      }
    }
  }

  translate(key: keyof TranslationDictionary | string): string {
    const dict = this.t();
    const k = key as keyof TranslationDictionary;
    return dict[k] ?? TRANSLATIONS.EN[k] ?? key;
  }
}
